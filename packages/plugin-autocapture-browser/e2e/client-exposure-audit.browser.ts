/**
 * One complete set of settings, in the same shape regardless of whether it is
 * the SDK baseline, what the audit ran with, or what the audit recommends.
 * Keeping the three in one shape is what makes them diffable side by side.
 */
type ConfigSnapshot = {
  cssSelectorAllowlist: string[];
  exposureDuration: number;
  elementSelector: {
    enabled: boolean;
    shadowDomEnabled: boolean;
    maxShadowDomDepth: number;
    autogeneratedIdPatterns: string[];
    unstableClassPatterns: string[];
  };
};

/**
 * Shared by both change kinds. `harnessControlled` marks the fields the harness
 * must override to do its job, so an audited value that differs from the SDK
 * default there says nothing about how the customer is configured.
 */
type ChangeBase = {
  field: string;
  changed: boolean;
  harnessControlled: boolean;
  reason: string;
};

type ConfigValue = string[] | number | boolean;

type ScalarChange = ChangeBase & {
  kind: 'value';
  sdkDefault: number | boolean;
  audited: number | boolean;
  recommended: number | boolean;
};

/**
 * List fields carry only the delta. The full arrays live once each in
 * `sdkDefaults`, `audited`, and `recommended` rather than three more times here.
 */
type ListChange = ChangeBase & {
  kind: 'list';
  entryCount: { sdkDefault: number; audited: number; recommended: number };
  added: string[];
  removed: string[];
};

type ConfigChange = ScalarChange | ListChange;

type AllowlistAddition = {
  selector: string;
  matchedElements: number;
  broad: boolean;
  examples: string[];
  reason: string;
};

type SettingsComparison = {
  hasRecommendedChanges: boolean;
  auditedMatchesSdkDefaults: boolean;
  auditedCustomizations: string[];
  sdkDefaults: ConfigSnapshot;
  audited: ConfigSnapshot;
  recommended: ConfigSnapshot;
  changes: ConfigChange[];
  allowlistAdditions: AllowlistAddition[];
  apply: {
    remoteConfigKey: string;
    remoteConfigPayload: ConfigSnapshot['elementSelector'];
    sdkOptions: { cssSelectorAllowlist: string[]; exposureDuration: number };
  };
  notes: string[];
};

